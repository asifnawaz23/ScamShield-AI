analyzeRouter.post('/analyze/image', imageLimiter, optionalAuth, async (req, res, next) => {
  try {
    const dataUrl = req.body?.dataUrl;
    const visibleText = sanitizeText(req.body?.visibleText);
    if (!isValidDataUrl(dataUrl)) {
      return res.status(400).json({
        error: 'Please attach a valid PNG, JPG or WEBP image under 5 MB.',
      });
    }
    const { result, mode, aiUsed } = await analyzeImageWithFallback({ dataUrl, visibleText });

    // Check reputation of any URLs found in the extracted visual text
    let reputationResult = null;
    const extractedUrl = extractFirstUrl(visibleText) || extractFirstUrl(result?.visualScan?.extracted?.urls?.[0]);
    if (extractedUrl) {
      reputationResult = await checkReputation(extractedUrl).catch(() => null);
    }

    const id = randomUUID();
    const payload = {
      id,
      ...result,
      type: 'image',
      inputSummary: (visibleText || 'uploaded screenshot (illustrative scan)').slice(0, 90),
      mode,
      aiUsed,
      visualSource: result.visualScan ? 'scan' : undefined,
      sampleLabel: mode === 'demo' ? 'Demo Mode' : 'Live AI',
      createdAt: new Date().toISOString(),
      reputationResult,
      limitations: buildLimitations('image', Boolean(reputationResult), aiUsed),
    };
    saveAnalysis(payload, req.user?.id);
    res.json({ ok: true, id, analysis: payload, mode, aiUsed });
  } catch (err) {
    next(err);
  }
});

analyzeRouter.post('/generate-safe-reply', analyzeLimiter, async (req, res, next) => {
  try {
    const content = sanitizeText(req.body?.content);
    const category = sanitizeText(req.body?.category);
    const { result } = await analyzeWithFallback({
      content: content || category || 'a suspicious message',
      type: 'text',
    });
    res.json({ ok: true, safeReply: result.safeReply });
  } catch (err) {
    next(err);
  }
});